// Copies the extension's optimizer into desktop/src/vendor/optimizer/.
// Vendored files are NEVER edited by hand; re-run this instead.
// Refuses to run if the source files have uncommitted changes, so the vendored
// copy always matches a real commit recorded in SYNC.json.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const FILES = [
  'prompt-rules-db.js',
  'token-counter.js',
  'prompt-optimizer.js',
  'prompt-generator.js',
];

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const srcDir = join(repoRoot, 'extension', 'lib');
const destDir = join(here, '..', 'src', 'vendor', 'optimizer');

const git = (...args) =>
  execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8' }).trim();

const rel = FILES.map((f) => `extension/lib/${f}`);
const dirty = git('status', '--porcelain', '--', ...rel);
if (dirty) {
  console.error('Refusing to sync: uncommitted changes in the extension optimizer files:\n' + dirty);
  process.exit(1);
}

mkdirSync(destDir, { recursive: true });
const sha256 = {};
for (const f of FILES) {
  copyFileSync(join(srcDir, f), join(destDir, f));
  sha256[f] = createHash('sha256').update(readFileSync(join(destDir, f))).digest('hex');
}

const sync = {
  _comment: 'GENERATED by scripts/sync-optimizer.mjs. Do not edit these files or this manifest by hand.',
  sourceCommit: git('rev-parse', 'HEAD'),
  syncedAt: new Date().toISOString(),
  sha256,
};
writeFileSync(join(destDir, 'SYNC.json'), JSON.stringify(sync, null, 2) + '\n');
console.log(`Synced ${FILES.length} files from commit ${sync.sourceCommit.slice(0, 10)}`);
